#!/usr/bin/env python3
"""Bundle runs.json, manifests, and reports for file:// dashboard use."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def read_json(path: Path):
    return json.loads(path.read_text())


def main() -> None:
    run_index = read_json(ROOT / "runs.json")
    bundled_runs = []

    for run in run_index.get("runs", []):
        manifest_path = ROOT / run["manifest"]
        manifest = read_json(manifest_path)
        reports = []
        for entry in manifest.get("reports", []):
            report_path = manifest_path.parent / entry["file"]
            reports.append(
                {
                    "label": entry["label"],
                    "fileName": entry["file"],
                    "data": read_json(report_path),
                }
            )
        bundled_runs.append(
            {
                "index": run,
                "manifest": manifest,
                "reports": reports,
            }
        )

    payload = json.dumps(bundled_runs, separators=(",", ":"), ensure_ascii=True)
    output = (
        "// Generated by generate-embedded-runs.py. Do not edit manually.\n"
        f"window.BENCHMARK_EMBEDDED_RUNS={payload};\n"
    )
    (ROOT / "embedded-runs.js").write_text(output)
    print(f"Bundled {len(bundled_runs)} run(s) into {ROOT / 'embedded-runs.js'}")


if __name__ == "__main__":
    main()
